//                                    |
//                              solveIssues()
//                                    |
//   Мерей (Тараз) ------react(false)-+--> Мерей: НЕ доволен
//
//  ЧАСТЬ 2
//   Баку (Тараз) --travel()--> Баку (Алматы)
//        |
//        | giveMoney(100000)
//        v
//   Баку: 0 тенге        Мерей: 100000 тенге
//
//  ЧАСТЬ 3
//   Рус: 0 тенге   Мерей: 100000 тенге
//        \               /
