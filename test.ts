// ============================================================
// ИСТОРИЯ:
//   1. Баку приехал в Тараз и решил вопросы,
//      но Мерей не был доволен.
//   2. Баку вернулся в Алматы и отдал деньги Мерею.
//   3. Рус поделил эти деньги с Мереем.
// ============================================================


// ------------------------------------------------------------
// ШАГ 1. ОПИСЫВАЕМ ТИП "ЧЕЛОВЕК"
// Тип - это шаблон: какие поля есть у человека и какого они вида.
// ------------------------------------------------------------
type Person = {
  name: string;      // имя          - текст
  city: string;      // город        - текст
  isHappy: boolean;  // доволен ли?  - true (да) или false (нет)
  money: number;     // деньги (тенге) - число   <-- НОВОЕ поле
};


// ------------------------------------------------------------
// ШАГ 2. СОЗДАЁМ ГЕРОЕВ ИСТОРИИ
// Каждый герой - объект по шаблону Person.
// ------------------------------------------------------------

// Баку: живёт в Алматы, настроение хорошее, у него есть деньги
const baku: Person = {
  name: "Баку",
  city: "Алматы",
  isHappy: true,
  money: 100000
};

// Мерей: живёт в Таразе, пока доволен, денег нет
const merey: Person = {
  name: "Мерей",
  city: "Тараз",
  isHappy: true,
  money: 0
};

// Рус: живёт в Алматы, денег пока нет   <-- НОВЫЙ герой
const rus: Person = {
  name: "Рус",
  city: "Алматы",
  isHappy: true,
  money: 0
};

// Список вопросов, которые нужно решить (массив строк)
const issues: string[] = ["документы", "договор", "оплата"];


// ------------------------------------------------------------
// ШАГ 3. ФУНКЦИИ - ДЕЙСТВИЯ В ИСТОРИИ
// Каждая функция: принимает данные -> возвращает результат.
// Исходного человека они НЕ меняют, а возвращают новую копию.
// ------------------------------------------------------------

// Действие 1: ПРИЕХАТЬ в другой город
//   вход:  человек + город назначения
//   выход: тот же человек, но с новым городом
function travel(p: Person, destination: string): Person {
  return { ...p, city: destination };
  //       ^^^^  "..." копирует все поля p (имя, город, настроение, деньги),
  //             а потом city заменяется на новый город
}

// Действие 2: РЕШИТЬ вопросы
//   вход:  человек + список вопросов
//   выход: готовая фраза (текст)
function solveIssues(p: Person, list: string[]): string {
  return `${p.name} решил вопросы: ${list.join(", ")}`;
  //      ^ шаблонная строка: ${...} подставляет значения в текст
  //                                  ^ join склеивает массив через запятую
}

// Действие 3: ОТРЕАГИРОВАТЬ (поменять настроение)
//   вход:  человек + доволен ли он (true/false)
//   выход: тот же человек, но с новым настроением
function react(p: Person, satisfied: boolean): Person {
  return { ...p, isHappy: satisfied };
}

// Действие 4: ОТДАТЬ деньги                      <-- НОВОЕ
//   вход:  кто отдаёт, кто получает, сколько
//   выход: ДВА человека: [отдавший, получивший] с обновлёнными деньгами
function giveMoney(
  from: Person,
  to: Person,
  amount: number
): [Person, Person] {
  return [
    { ...from, money: from.money - amount },  // у отдавшего стало меньше
    { ...to, money: to.money + amount }       // у получившего стало больше
  ];
}

// Действие 5: ПОДЕЛИТЬ деньги поровну              <-- НОВОЕ
//   вход:  двое людей
//   выход: двое людей, у каждого ровно половина общей суммы
function splitMoney(a: Person, b: Person): [Person, Person] {
  const half = (a.money + b.money) / 2;  // общая сумма, делённая на два
  return [
    { ...a, money: half },
    { ...b, money: half }
  ];
}


// ------------------------------------------------------------
// ШАГ 4. РАЗВИВАЕМ СЮЖЕТ (запускаем действия по порядку)
// ------------------------------------------------------------

// ----- ЧАСТЬ 1: поездка в Тараз -----

// 4.1  Баку едет в город, где живёт Мерей (Тараз)
const bakuInTaraz = travel(baku, merey.city);
console.log(`${bakuInTaraz.name} приехал в ${bakuInTaraz.city}`);
// -> Баку приехал в Тараз

// 4.2  Баку решает вопросы
console.log(solveIssues(bakuInTaraz, issues));
// -> Баку решил вопросы: документы, договор, оплата

// 4.3  Мерей реагирует: false = НЕ доволен
const mereyAfter = react(merey, false);

// Если isHappy == true  -> пишем "доволен"
// Иначе (false)         -> пишем "не был доволен"
console.log(
  mereyAfter.isHappy
    ? `${mereyAfter.name} доволен`
    : `${mereyAfter.name} не был доволен`
);
// -> Мерей не был доволен


// ----- ЧАСТЬ 2: возвращение и деньги -----

// 4.4  Баку возвращается в Алматы
const bakuHome = travel(bakuInTaraz, "Алматы");
console.log(`${bakuHome.name} вернулся в ${bakuHome.city}`);
// -> Баку вернулся в Алматы

// 4.5  Баку отдаёт все свои деньги Мерею
//      Результат приходит парой, поэтому разбираем её на две переменные:
const [bakuPaid, mereyPaid] = giveMoney(bakuHome, mereyAfter, bakuHome.money);
console.log(`${bakuPaid.name} отдал ${mereyPaid.name} ${mereyPaid.money} тенге`);
// -> Баку отдал Мерей 100000 тенге
console.log(`У ${bakuPaid.name} осталось ${bakuPaid.money} тенге`);
// -> У Баку осталось 0 тенге


// ----- ЧАСТЬ 3: Рус делит деньги с Мереем -----

// 4.6  Рус и Мерей делят деньги поровну
const [rusFinal, mereyFinal] = splitMoney(rus, mereyPaid);
console.log(`${rusFinal.name} поделил деньги с ${mereyFinal.name}`);
// -> Рус поделил деньги с Мерей
console.log(`У ${rusFinal.name}: ${rusFinal.money} тенге`);
// -> У Рус: 50000 тенге
console.log(`У ${mereyFinal.name}: ${mereyFinal.money} тенге`);
// -> У Мерей: 50000 тенге


